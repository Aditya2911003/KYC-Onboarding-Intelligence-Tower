def load_customer(customer_id: str) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Fetch one case row and its documents by exact CustomerID (parameterised)."""
    case = data.query("SELECT * FROM mart_case_detail WHERE customer_id = ?", (customer_id,))
    docs = data.query(
        "SELECT doc_type, verified, confidence, issue_country, expiry_date "
        "FROM mart_customer_docs WHERE customer_id = ? ORDER BY doc_type",
        (customer_id,),
    )
    return case, docs


def _rule_path(row: pd.Series) -> pd.DataFrame:
    """Evaluate the policy rules in order and show which fired and why."""
    steps = [
        ("R1 Sanctions screening", "Sanctioned?", bool(row.is_sanctioned), "Reject"),
        ("R2 PEP enhanced due diligence", "Politically exposed person?", bool(row.is_pep), "Enhanced Due Diligence"),
        ("R3 High-risk escalation", "Risk tier = High?", row.risk_category == "High", "EDD or Manual Review"),
        (
            "R4 Document sufficiency",
            f"Verified documents < 4? ({int(row.verified_docs)})",
            int(row.verified_docs) < 4,
            "Pending Documents",
        ),
        ("R5 Standard approval", "Otherwise", True, "Approve"),
    ]
    out, fired = [], False
    for rule, test, hit, outcome in steps:
        status = "not evaluated" if fired else ("FIRED" if hit else "passed")
        out.append({"rule": rule, "test": test, "result": status, "outcome if fired": outcome})
        fired = fired or hit
    return pd.DataFrame(out)


def render_customer_360(customer_id: str, key_prefix: str = "c360") -> None:
    """Profile card, documents, rule path, risk score and simulated timeline."""
    case, docs = load_customer(customer_id)
    if case.empty:
        st.warning(f"No customer found with ID {customer_id}. IDs look like C000123 (exact match).")
        return
    row = case.iloc[0]
    agree = "agrees" if bool(row.engine_agrees) else "DISAGREES"
    st.markdown(
        f"**{html.escape(customer_id)}** · case {html.escape(str(row.case_id))} · synthetic profile "
        f"(names and dates of birth are not published)"
    )
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Labelled decision", str(row.decision))
    c2.metric("Rule engine", str(row.engine_decision), help=f"Engine {agree} with the label.")
    c3.metric("Risk tier", str(row.risk_category))
    c4.metric("Verified documents", f"{int(row.verified_docs)} / 5")
    profile = pd.DataFrame(
        {
            "attribute": [
                "Country",
                "Occupation",
                "Account type",
                "Age band",
                "Income quintile",
                "PEP",
                "Sanctioned",
                "AML flag",
                "Identity verified",
                "Address verified",
                "Last review",
                "Review overdue",
            ],
            "value": [
                row.country,
                row.occupation,
                row.account_type,
                row.age_band,
                f"Q{int(row.income_quintile)}",
                _yn(row.is_pep),
                _yn(row.is_sanctioned),
                _yn(row.aml_flag),
                _yn(row.identity_verified),
                _yn(row.address_verified),
                str(pd.Timestamp(row.last_updated).date()),
                f"{_yn(row.review_overdue)} ({int(row.days_since_review)} days)",
            ],
        }
    )
    left, right = st.columns([1, 1.3])
    with left:
        st.markdown("**Profile card**")
        st.dataframe(profile, hide_index=True, width="stretch", height=455)
    with right:
        st.markdown("**The 5 documents** (OCR confidence; no OCR text is published)")
        st.dataframe(
            tidy(docs),
            hide_index=True,
            width="stretch",
            column_config={
                "confidence": st.column_config.ProgressColumn("confidence", min_value=0.0, max_value=1.0, format="%.2f")
            },
        )
        breaches = [
            name
            for name, flag in (
                ("identity", row.breach_approved_no_identity),
                ("address", row.breach_approved_no_address),
                ("missing document", row.breach_approved_missing_doc),
            )
            if bool(flag)
        ]
        if breaches:
            st.error(f"Control breach: approved despite failed {', '.join(breaches)} check.")
        else:
            st.success("No control breach recorded for this case.")
    st.markdown("**Rule path** (recovered policy, evaluated in precedence order)")
    st.dataframe(_rule_path(row), hide_index=True, width="stretch")

    score, parts = kpis.risk_score_breakdown(
        bool(row.is_sanctioned),
        bool(row.is_pep),
        str(row.risk_category),
        bool(row.identity_verified),
        bool(row.address_verified),
        int(row.verified_docs),
    )
    a, b = st.columns([1, 1.4])
    with a:
        st.markdown(f"**Additive risk score: {score} / 100**")
        if parts:
            fig = go.Figure(
                go.Bar(
                    x=[p for _, p in parts],
                    y=[n for n, _ in parts],
                    orientation="h",
                    marker_color=BAD,
                    text=[f"+{p}" for _, p in parts],
                    textposition="auto",
                    hovertemplate="%{y}: +%{x}<extra></extra>",
                )
            )
            fig.update_layout(
                height=60 + 34 * len(parts),
                yaxis=dict(autorange="reversed"),
                template="kyc_pbi",
                paper_bgcolor=TILE,
                plot_bgcolor=TILE,
            )
            st.plotly_chart(
                fig, key=f"{key_prefix}_score_{customer_id}", width="stretch", config=CHART_CONFIG, theme=None
            )
        else:
            st.write("No risk components present.")
        footnote(
            "Illustration only, not a calibrated model: sanction 100, PEP 30, High risk 25, identity "
            "unverified 10, address unverified 10, each unverified document 5, capped at 100."
        )
    with b:
        st.markdown(f"**Case timeline** {sim_pill()}", unsafe_allow_html=True)
        opened = pd.Timestamp(row.opened_date)
        closed = opened + pd.Timedelta(days=float(row.tat_days))
        timeline = pd.DataFrame(
            {
                "event": [
                    "Case opened",
                    "Assigned",
                    "Decision recorded" if not row.is_open else "Still open at AS_OF",
                    "SLA target",
                ],
                "when": [
                    opened.date(),
                    opened.date(),
                    closed.date(),
                    (opened + pd.Timedelta(days=int(row.sla_days))).date(),
                ],
                "detail": [
                    f"via {row.channel}",
                    str(row.assigned_to),
                    f"{fmt_days(float(row.tat_days))} turnaround",
                    f"{int(row.sla_days)} days · {'BREACHED' if bool(row.sla_breached) else 'met'}",
                ],
            }
        )
        st.dataframe(tidy(timeline), hide_index=True, width="stretch")
        footnote(SIM_NOTE)


def _yn(value: object) -> str:
    return "Yes" if bool(value) else "No"


@st.dialog("Customer 360 (drill-through)", width="large")
def customer_360_dialog(customer_id: str) -> None:
    """Drill-through dialog opened from any case table."""
    render_customer_360(customer_id, key_prefix="dlg")


def valid_customer_id(text: str) -> bool:
    """Exact CustomerID format check (C + 6 digits) before any query runs."""
    return bool(CUSTOMER_ID_RE.match(text.strip()))


def kpi_snapshot(filters: Filters) -> dict:
    """All headline KPIs for a filter state in one parameterised SQL statement."""
    where, params = data.where_clause(filters)
    select = ", ".join(f"{sql} AS {name}" for name, sql in kpis.KPI_SQL.items())
    frame = data.query(f"SELECT {select} FROM mart_case_detail {where}", params)
    return {k: (None if pd.isna(v) else v) for k, v in frame.iloc[0].to_dict().items()}


def previous_snapshot(filters: Filters) -> dict | None:
    """KPIs for the previous equal-length period (None when it has no cases)."""
    prev_start, prev_end = kpis.previous_period(filters.start, filters.end)
    prev = kpi_snapshot(filters.with_dates(prev_start, prev_end))
    return prev if prev.get("cases") else None


def headline_finding() -> None:
    """Render the lead finding over the full population (independent of slicers)."""
    full_start, full_end = data.date_bounds()
    overall = kpi_snapshot(Filters(full_start, full_end))
    headline(
        f"<b>Headline finding (all {fmt_int(overall['cases'])} cases):</b> the decision logic is sound "
        f"(<b>{fmt_pct(overall['engine_agreement'])}</b> rule-engine reconciliation) but the verification "
        f"controls are not enforced (<b>{fmt_pct(overall['control_breach_rate'])}</b> of approvals carry a "
        "failed identity or address flag). This is a <b>control gap, not a logic error</b>."
    )


def kpi_delta(name: str, now: dict, prev: dict | None) -> float | None:
    """Period-over-period delta for one KPI."""
    if prev is None:
        return None
    return kpis.period_delta(now.get(name), prev.get(name))


def good_bad_color(ok: bool) -> str:
    """Green when good, red when bad."""
    return GOOD if ok else BAD


