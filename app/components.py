def tidy(frame: pd.DataFrame) -> pd.DataFrame:
    """Display copy: dates without times (months as YYYY-MM)."""
    out = frame.copy()
    for col in out.columns:
        if pd.api.types.is_datetime64_any_dtype(out[col]):
            fmt = "%Y-%m" if col.endswith("month") else "%Y-%m-%d"
            out[col] = out[col].dt.strftime(fmt)
    return out


def table(frame: pd.DataFrame, **kwargs: object) -> None:
    """st.dataframe with tidy dates and thousands separators on numeric columns."""
    shown = tidy(frame)
    config: dict = {}
    for col in shown.columns:
        if pd.api.types.is_integer_dtype(shown[col]) and not col.startswith(("rank", "stage_order")):
            config[col] = st.column_config.NumberColumn(format="localized")
    config.update(kwargs.pop("column_config", None) or {})  # type: ignore[arg-type]
    kwargs.setdefault("hide_index", True)
    kwargs.setdefault("width", "stretch")
    st.dataframe(shown, column_config=config, **kwargs)  # type: ignore[arg-type]


def case_table(frame: pd.DataFrame, key: str, height: int = 320) -> None:
    """Case table where clicking a row opens Customer 360 in a dialog (drill-through)."""
    nonce_key = f"dt_nonce_{key}"
    nonce = st.session_state.get(nonce_key, 0)
    event = st.dataframe(
        tidy(frame),
        key=f"dt_{key}_{nonce}",
        on_select="rerun",
        selection_mode="single-row",
        hide_index=True,
        width="stretch",
        height=height,
    )
    rows = event.selection.rows if event and event.selection else []
    st.caption("Select a row to drill through to Customer 360.")
    if rows:
        customer_id = str(frame.iloc[rows[0]]["customer_id"])
        st.session_state[nonce_key] = nonce + 1  # clear the selection on the next run
        customer_360_dialog(customer_id)


