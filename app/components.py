def kpi_card(
    key: str,
    label: str,
    value: str,
    delta: float | None = None,
    polarity: int = 1,
    simulated: bool = False,
    foot: str = "",
) -> None:
    """Power BI-style KPI card with a coloured, arrowed delta (never colour alone)."""
    if delta is None:
        delta_html = f'<span class="kpi-delta" style="color:{MUTED}">vs prior period: n/a</span>'
    else:
        good = (delta >= 0) == (polarity >= 0) if delta != 0 else True
        arrow = "▲" if delta > 0 else ("▼" if delta < 0 else "■")
        color = GOOD if good else BAD
        word = "better" if good else "worse"
        delta_html = (
            f'<span class="kpi-delta" style="color:{color}">{arrow} {abs(delta):.1%} vs prior period ({word})</span>'
        )
    pill = sim_pill() if simulated else ""
    with st.container(key=f"kpi_{key}"):
        st.markdown(
            f'<div class="kpi-label">{html.escape(label)}{pill}</div>'
            f'<div class="kpi-value">{html.escape(value)}</div>{delta_html}'
            f'<div class="kpi-foot">{html.escape(foot)}</div>',
            unsafe_allow_html=True,
        )


@contextmanager
def tile(key: str, title: str, subtitle: str = "", simulated: bool = False) -> Iterator[None]:
    """White bordered tile with a title, optional subtitle and SIMULATED pill."""
    with st.container(key=f"tile_{key}"):
        pill = sim_pill() if simulated else ""
        st.markdown(
            f'<div class="tile-title">{html.escape(title)}{pill}</div>'
            + (f'<div class="tile-sub">{html.escape(subtitle)}</div>' if subtitle else ""),
            unsafe_allow_html=True,
        )
        yield
        if simulated:
            footnote(SIM_NOTE)


def chart(fig: go.Figure, key: str, height: int = 300) -> None:
    """Render a non-interactive Plotly chart with the shared config."""
    fig.update_layout(height=height, template="kyc_pbi", paper_bgcolor=TILE, plot_bgcolor=TILE)
    st.plotly_chart(fig, key=key, width="stretch", config=CHART_CONFIG, theme=None)


def xf_chart(fig: go.Figure, key: str, slicer: str, height: int = 300) -> None:
    """Render a chart whose clicks cross-filter every page.

    Each clickable trace must carry the slicer value in ``customdata[0]``.
    Clicking the only selected value clears the filter (Power BI behaviour).
    """
    fig.update_layout(
        height=height, clickmode="event+select", template="kyc_pbi", paper_bgcolor=TILE, plot_bgcolor=TILE
    )
    nonce = st.session_state.get("xf_nonce", 0)
    event = st.plotly_chart(
        fig,
        key=f"xf_{key}_{nonce}",
        on_select="rerun",
        selection_mode="points",
        width="stretch",
        config=CHART_CONFIG,
        theme=None,
    )
    points = event.selection.points if event and event.selection else []
    if points:
        custom = points[0].get("customdata")
        value = custom[0] if isinstance(custom, (list, tuple)) and custom else custom
        if value is not None:
            toggle_filter(slicer, str(value))
            st.session_state["xf_nonce"] = nonce + 1
            st.rerun()
    st.caption(f"Click a mark to cross-filter by {SLICERS[slicer][1].lower()}; click it again to clear.")


def donut(labels: Sequence[str], values: Sequence[float], colors: Sequence[str], center: str) -> go.Figure:
    """Build a selectable donut from dense scatter markers on a ring.

    Plotly pie slices do not emit selection events in Streamlit, so the ring is
    built from markers (which do) to support click-to-cross-filter.
    """
    fig = go.Figure()
    total = float(sum(values)) or 1.0
    start = 0.0
    for label, value, color in zip(labels, values, colors, strict=True):
        span = value / total * 360
        n = max(int(span * 1.5), 2)
        pad = min(0.4, span / 4)
        theta = np.radians(90 - np.linspace(start + pad, start + span - pad, n))
        fig.add_trace(
            go.Scatter(
                x=np.cos(theta),
                y=np.sin(theta),
                mode="markers",
                name=f"{label} ({value / total:.1%})",
                marker=dict(size=26, color=color, line=dict(width=0)),
                customdata=[[label]] * n,
                hovertemplate=f"<b>{html.escape(label)}</b><br>{value:,.0f} cases ({value / total:.1%})<extra></extra>",
            )
        )
        start += span
    fig.update_xaxes(visible=False, range=[-1.45, 1.45], fixedrange=True)
    fig.update_yaxes(visible=False, range=[-1.3, 1.3], scaleanchor="x", fixedrange=True)
    fig.update_layout(
        showlegend=True,
        legend=dict(orientation="v", x=1.0, y=0.5, xanchor="left", yanchor="middle"),
        annotations=[dict(text=center, x=0, y=0, showarrow=False, font=dict(size=15))],
        dragmode=False,
        margin=dict(l=0, r=0, t=0, b=0),
    )
    return fig


def decision_bar_colors(decisions: Sequence[str]) -> list[str]:
    """Return the fixed decision colours for a list of decisions."""
    return [DECISION_COLORS.get(d, MUTED) for d in decisions]


