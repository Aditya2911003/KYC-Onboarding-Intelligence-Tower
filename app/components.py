def inject_css() -> None:
    """Apply the design-system CSS once per run."""
    st.markdown(CSS, unsafe_allow_html=True)


def sim_pill() -> str:
    """HTML for the purple SIMULATED pill."""
    return '<span class="sim-pill" title="Derived from the seeded simulation, not from source data">SIMULATED</span>'


def real_pill() -> str:
    """HTML for the teal 'dataset' pill marking visuals computed from the real synthetic dataset."""
    return '<span class="real-pill" title="Computed from the source dataset">DATASET</span>'


