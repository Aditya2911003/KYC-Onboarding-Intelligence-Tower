def _sync(name: str) -> None:
    st.session_state[f"flt_{name}"] = list(st.session_state.get(f"w_{name}", []))


def _sync_dates() -> None:
    value = st.session_state.get("w_dates")
    if isinstance(value, (tuple, list)) and len(value) == 2:
        st.session_state["flt_dates"] = (value[0], value[1])


def _apply_preset(full_start: date, full_end: date) -> None:
    days = PRESETS.get(st.session_state.get("w_preset") or "All")
    if days is None:
        st.session_state["flt_dates"] = (full_start, full_end)
    else:
        st.session_state["flt_dates"] = (max(full_start, full_end - timedelta(days=days - 1)), full_end)


def _preset_for(dates: tuple[date, date], full_start: date, full_end: date) -> str:
    for label, days in PRESETS.items():
        start = full_start if days is None else max(full_start, full_end - timedelta(days=days - 1))
        if dates == (start, full_end):
            return label
    return "Custom"


def slicer_bar() -> Filters:
    """Render the report-level slicer bar and return the active filters."""
    full_start, full_end = data.date_bounds()
    init_state(full_start, full_end)
    with st.container(key="slicer_bar"):
        cols = st.columns([1.2, 1.6, 1, 1, 1, 1.1, 1.2, 1.0], vertical_alignment="bottom")
        st.session_state["w_preset"] = _preset_for(tuple(st.session_state["flt_dates"]), full_start, full_end)
        cols[0].selectbox(
            "Period",
            [*PRESETS, "Custom"],
            key="w_preset",
            on_change=_apply_preset,
            args=(full_start, full_end),
        )
        st.session_state["w_dates"] = tuple(st.session_state["flt_dates"])
        cols[1].date_input(
            "Opened date (SIMULATED)",
            key="w_dates",
            min_value=full_start,
            max_value=full_end,
            on_change=_sync_dates,
            format="YYYY-MM-DD",
        )
        for col, (name, (column, label)) in zip(cols[2:7], SLICERS.items(), strict=True):
            st.session_state[f"w_{name}"] = list(st.session_state[f"flt_{name}"])
            col.multiselect(
                label,
                data.distinct_values(column),
                key=f"w_{name}",
                on_change=_sync,
                args=(name,),
                placeholder="All",
            )
        cols[7].button(
            "Reset filters",
            key="reset_filters",
            help="All slicers back to All",
            on_click=reset_filters,
            args=(full_start, full_end),
            width="stretch",
            icon=":material/filter_alt_off:",
        )
    filters = current_filters(full_start, full_end)
    active = filters.active_count(full_start, full_end)
    if active:
        st.caption(f"{active} slicer(s) active — applied to every sliceable visual on every page.")
    return filters


def page_header(title: str, question: str, simulated: bool = False, slicers: bool = True) -> Filters | None:
    """Title band, optional SIMULATED pill and the slicer bar."""
    inject_css()
    pills = real_pill() + (sim_pill() if simulated else "")
    st.markdown(
        f'<div class="title-band"><div><h1>{html.escape(title)}</h1>'
        f'<div class="question">{html.escape(question)}</div></div>'
        f'<div>{pills}<span class="sim-pill" style="background:#5F6B6D">SYNTHETIC DATA</span></div></div>',
        unsafe_allow_html=True,
    )
    return slicer_bar() if slicers else None


def insight_strip(sentences: Sequence[str]) -> None:
    """Render 2-3 computed insight sentences under the page title."""
    items = "".join(f"<li>{html.escape(s)}</li>" for s in sentences if s)
    st.markdown(f'<div class="insight-strip"><ul>{items}</ul></div>', unsafe_allow_html=True)


def headline(text: str) -> None:
    """Prominent headline-finding banner."""
    st.markdown(f'<div class="headline">{text}</div>', unsafe_allow_html=True)


def flat_badge(text: str, flat: bool) -> None:
    """Red 'FLAT' notice above a chart whose groups do not differ meaningfully."""
    if flat:
        st.markdown(
            f'<div style="color:{BAD};font-weight:700;font-size:12px">{html.escape(text)}</div>', unsafe_allow_html=True
        )


def footnote(text: str) -> None:
    """Small grey footnote."""
    st.markdown(f'<div class="footnote">{html.escape(text)}</div>', unsafe_allow_html=True)


